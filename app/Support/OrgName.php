<?php

namespace App\Support;

/**
 * Название организации коротко — форма аббревиатурой (16.11.2026, строка покупателя на странице сделки менеджера:
 * «ОБЩЕСТВО С ОГРАН…» резалось многоточием раньше, чем начиналось само имя). Только для показа — в документах полное.
 */
final class OrgName
{
    private const FORMS = [
        'публичное акционерное общество' => 'ПАО',
        'непубличное акционерное общество' => 'АО',
        'акционерное общество' => 'АО',
        'общество с ограниченной ответственностью' => 'ООО',
        'индивидуальный предприниматель' => 'ИП',
    ];

    public static function short(?string $name): string
    {
        $name = trim((string) $name);
        foreach (self::FORMS as $long => $abbr) {
            $name = preg_replace('/^'.preg_quote($long, '/').'\b\s*/iu', $abbr.' ', $name, 1) ?? $name;
        }

        return trim($name);
    }
}
