<?php

namespace App\Support\Table;

/**
 * Что за столбец — из этого одним местом его место в строке, выравнивание и цвет (30.10.2026, владелец: «должна же быть
 * какая-то единая логика, а не хаос»: дата то в середине, то справа, номер убытка то за названием, то после почты).
 *
 * Слева, по левому краю: название → код (вендор и № убытка, №, ДЛ, счёт — приглушённым) → что с ним (состояние, этап,
 * статус, тип). Последний столбец левой группы забирает запас ширины — пустота встаёт между группами.
 * Справа, по правому краю: кто → где → сколько → когда (дата — самая правая). У парковки свой порядок (`Table::PARK`).
 */
enum ColRole: int
{
    case Pick = 0;
    /** Тип строки, когда в списке смешаны разные (заявки парковки «Все»): первым, перед названием. */
    case Kind = 8;
    case Title = 1;
    case Code = 2;
    case State = 3;
    case Who = 4;
    case Place = 5;
    case Amount = 6;
    case When = 7;

    /** Правая группа — по правому краю. */
    public function right(): bool
    {
        return in_array($this, [self::Who, self::Place, self::Amount, self::When], true);
    }
}
