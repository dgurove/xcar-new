    /** Чью часть показать: `?who=` или по вкладкам, за которые человек отвечает (`TabOwner`); `all` — всё. */
    public static function who(?string $asked, User $user): string
    {
        if ($asked === 'all' || isset(self::PEOPLE[$asked])) {
            return $asked;
        }
        $tabs = TabOwner::presetsOf($user);

        return match (true) {
            in_array('bids', $tabs, true) => 'andrey',
            in_array('payout', $tabs, true) && ! in_array('letter', $tabs, true) => 'katya',
            default => 'team',
        };
    }
