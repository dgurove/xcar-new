<?php

namespace App\Offers;

use App\Workflow\Outcome;
use Illuminate\Support\HtmlString;

/**
 * Окно «Вы уверены?» перед шагами, которые потом не отыграть (19.11.2026, владелец: «менеджеры на шару эту кнопку нажимают, а
 * потом говорят „случайно нажал“»; «везде, где менеджер жмёт, что отказался, передумал… если нажать, то всё тютю»; заголовок —
 * «Вы уверены?», а не пересказ кнопки: «масло масляное»; о других менеджерах и возврате в продажу не пишем). Вид один: вопрос,
 * что будет, «Да, …» и «Ещё подумаю» (`confirm.js` берёт всё с нажатой кнопки). Одна дверь для текстов — своих копий в видах нет.
 * Где: «Беру в работу» и «Осмотрел, берём», отказы от сделки, ставка, отзыв ставки, отказ от контрпредложения и от новой цены,
 * «Отправить цену», гараж «Забрал», «Продаю», «Продана»; Telegram — те же тексты в переспросе (`UpdateHandler::confirmed`).
 */
final class Warnings
{
    public const TITLE = 'Вы уверены?';

    public const CANCEL = 'Ещё подумаю';

    /**
     * «Беру в работу», «Осмотрел, берём», «Всё в порядке, берём» — текст начальника, дословно (19.11.2026). Окно — три кнопки
     * (`x-deal.take-sheet`: «Да, беру в работу», «Ещё подумаю…», «Отказываюсь»), в Telegram — переспрос `UpdateHandler::turn`.
     */
    public const TAKE = "ТС реализуется в состоянии «как есть» и «где есть».\n\n"
        ."Подтверждение означает ознакомление и согласие с историей ТС и комплектацией по VIN-коду.\n\n"
        .'После нажатия на эту кнопку любые отказы не принимаются.';

    /** Отказ от идущей сделки: «Отказываюсь», «После осмотра не берём», «Отказываюсь» от новой цены в сделке. */
    public const DEAL_OFF = 'Сделка отменится. Взять это ТС обратно, возможно, не получится.';

    /** Подтверждение снимается: «Отозвать», отказ от контрпредложения, «Отказываюсь» от новой цены по подтверждению. */
    public const BID_OFF = 'Ваше подтверждение снимется. Заново подтвердить, возможно, не получится.';

    /** Ставка обычной ценой (`bid_controller`). */
    public const BID = 'Если подтверждение примут, откроется сделка по этой цене.';

    /**
     * Ставка с «+ Доп. запрос…» (27.11.2026, Корабельников: «как отказа быть не может, если я запрашиваю осмотр»): берёт ли он ТС,
     * решает после ответа поставщика (`ExtraAsk::labels`). `{what}` — отмеченное словами («ПТС и осмотр»); текст — владельца, дословно.
     */
    public const BID_EXTRA = 'Если подтверждение примут, мы сразу запросим у поставщика {what}. Брать ли в работу, можно будет решить после ответа';

    /** «Беру в работу» на доп. просьбе, пока поставщик не ответил (27.11.2026) — над `TAKE`. */
    public const TAKE_EARLY = 'Ответа поставщика на доп. запрос ещё нет. Можно дождаться его и решить потом.';

    /** Гараж «Забрал» (`SelfPickup`): вернуть — «Ещё не вывезли» у сотрудника. */
    public const PICKED = 'Вывоз закроется. Вернуть сможет только администратор.';

    /** Гараж «Продаю» и «Продана»: «Не продана» — у сотрудника. */
    public const SOLD = 'Изменить цену или отменить продажу сможет только администратор.';

    /**
     * Подбор отдельной ссылкой у Совкомбанка (25.11.2026, владелец: «Совком НИКОГДА не должен быть отдельно оплата подбора ссылкой»,
     * переключатель оставить, но с окном): шторка «Цена и вознаграждение», `confirm_pick_controller`.
     */
    public const SELECTION_APART_SOVCOM = "У Совкомбанка подбор всегда входит в счёт за ТС, отдельной ссылкой его не выставляем.\n\n"
        .'Покупатель получит два счёта: за ТС без подбора и ссылку на подбор.';

    /** Берёт ли менеджер ТС этим ответом шага: «Беру в работу», «Покупаю», после осмотра — «Осмотрел, берём». */
    public static function takes(Outcome $exit): bool
    {
        return $exit->takes() || ($exit->actor === \App\Workflow\Actor::Manager && mb_strtolower(trim($exit->label)) === 'осмотрел, берём');
    }

    /**
     * Атрибуты кнопки для `confirm.js`; `danger` — «да» красным (отказы).
     *
     * @return array<string, string|null>
     */
    public static function attrs(?string $text, string $ok, bool $danger = false): array
    {
        return ['data-turbo-confirm' => self::TITLE, 'data-turbo-confirm-text' => $text, 'data-turbo-confirm-label' => $ok,
            'data-turbo-confirm-cancel' => self::CANCEL, 'data-turbo-confirm-danger' => $danger ? '1' : null];
    }

    /** Те же атрибуты строкой — для голой `<button>`. */
    public static function html(?string $text, string $ok, bool $danger = false): HtmlString
    {
        return new HtmlString(collect(self::attrs($text, $ok, $danger))->filter(fn ($v) => $v !== null)
            ->map(fn ($v, $k) => $k.'="'.e($v).'"')->implode(' '));
    }

    /** Переспрос в Telegram: вопрос и текст одним сообщением. */
    public static function telegram(?string $text): string
    {
        return self::TITLE.($text ? "\n\n".$text : '');
    }
}
