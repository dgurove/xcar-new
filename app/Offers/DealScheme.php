<?php

namespace App\Offers;

use App\Cars\HasLabels;

/**
 * Кому платят за ТС (05.10.2026). «Нам» — менеджер платит нам цену подтверждения, мы рассчитываемся со страховой
 * (Альфа, Совкомбанк). «Страхователю по ДКП» — покупатель менеджера платит закупочную собственнику сам по договору
 * купли-продажи, который собираем мы, а менеджер платит нам разницу за подбор и вознаграждение оставляет себе
 * (Т-Страхование). Выбирает админ при принятии, по умолчанию — от формата сделки вендора (`DealFormat::Direct`).
 */
enum DealScheme: string
{
    use HasLabels;

    case Ours = 'ours';
    case OwnerDkp = 'owner_dkp';

    public function label(): string
    {
        return match ($this) {
            self::Ours => 'Нам',
            self::OwnerDkp => 'Страхователю по ДКП',
        };
    }
}
