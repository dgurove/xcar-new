<?php

namespace App\Users;

/**
 * Слова для супер-покупателя (10.10.2026, владелец: «пусть он думает, что он просто покупатель»). Его сделки идут
 * маршрутами менеджеров, и этапы, просьбы, «чей ход» и уведомления говорят «менеджер»: «Согласие менеджера»,
 * «Ждём менеджера». Тексты маршрутов правит админ в редакторе, поэтому переводятся сами слова — там, где текст
 * маршрута выходит к нему: этап, просьба, кнопка шага, путь (`Wording::mine` в видах сделки) и уведомления
 * (`Notice::titleFor`/`textFor`). Чужой текст (описание ТС, ответы страховой, чат) не трогается: там «менеджер» —
 * чей-то другой.
 */
final class Wording
{
    /** Окончание «менеджер…» → окончание «покупател…» того же падежа и числа. */
    private const ENDINGS = ['' => 'ь', 'а' => 'я', 'у' => 'ю', 'ом' => 'ем', 'е' => 'е', 'ы' => 'и', 'ов' => 'ей', 'ам' => 'ям', 'ами' => 'ями', 'ах' => 'ях'];

    private const WORD = '/(?<![А-Яа-яЁё])([Мм])енеджер(ами|ах|ам|ов|ом|у|а|е|ы)?(?![А-Яа-яЁё])/u';

    /** Для того, кто смотрит страницу. */
    public static function mine(?string $text): ?string
    {
        return self::for(auth()->user(), $text);
    }

    public static function for(?User $user, ?string $text): ?string
    {
        return $text !== null && $user?->holdsAsBuyer() ? self::buyer($text) : $text;
    }

    /** «Согласие менеджера» → «Согласие покупателя». */
    public static function buyer(string $text): string
    {
        return preg_replace_callback(self::WORD, fn ($m) => ($m[1] === 'М' ? 'П' : 'п').'окупател'.self::ENDINGS[$m[2] ?? ''], $text) ?? $text;
    }

    /**
     * Дело без обращения — для сообщений менеджеру (11.11.2026, владелец: «ни на вы, ни на ты по возможности»): «Заберите
     * автомобиль» → «автомобиль можно забирать», «Укажите покупателя» → «нужно указать покупателя», «Подпишите и передайте
     * документы» → «нужно подписать и передать документы»; вопрос и фраза без повелительного — как есть. С маленькой буквы:
     * встаёт после «Привет,».
     */
    public static function neutral(?string $text): string
    {
        $text = trim((string) $text);
        $verbs = ['Укажите' => 'указать', 'Приложите' => 'приложить', 'Заполните' => 'заполнить', 'Подпишите' => 'подписать', 'Оплатите' => 'оплатить',
            'Назовите' => 'назвать', 'Выберите' => 'выбрать', 'Свяжитесь' => 'связаться', 'Заберите' => 'забрать', 'Передайте' => 'передать',
            'Отправьте' => 'отправить', 'Проверьте' => 'проверить', 'Подтвердите' => 'подтвердить', 'Сфотографируйте' => 'сфотографировать', 'Привезите' => 'привезти'];
        $special = ['Заберите автомобиль' => 'автомобиль можно забирать'];
        if (isset($special[$text])) {
            return $special[$text];
        }
        $first = strtok($text, ' ,');
        if (isset($verbs[$first])) {
            $rest = mb_substr($text, mb_strlen($first));
            foreach ($verbs as $imp => $inf) {
                $rest = preg_replace('/(?<=\s)'.mb_strtolower($imp).'(?=\s|$)/u', $inf, $rest);
            }

            return 'нужно '.$verbs[$first].$rest;
        }

        return $text === '' ? $text : mb_strtolower(mb_substr($text, 0, 1)).mb_substr($text, 1);
    }
}
