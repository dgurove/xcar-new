<?php

namespace App\Billing\Passport;

/**
 * Регистр распознанного паспорта (17.11.2026, владелец: «паспортные данные постоянно капсом распознаются — форматировать: каждое
 * слово с большой буквы, „г.“, „ул.“ и „д.“ маленькой»): место рождения и прописка — «ГОР. КАРАЧЕВ БРЯНСКОЙ ОБЛ.» → «гор. Карачев
 * Брянской обл.», «БРЯНСКАЯ ОБЛ. P-H БРЯНСКИЙ, УЛ. ФРУНЗЕ, Д.38» → «Брянская обл. р-н Брянский, ул. Фрунзе, д.38». «Кем выдан» —
 * заглавными, как в бланке (тот же день, владелец), этим правилом не форматируется.
 * - слово — с большой буквы, остальное строчными;
 * - сокращения адреса («г.», «ул.», «д.», «кв.», «обл.», «р-н», «пр-т», «пгт»…) и предлоги («по», «в», «на») — строчными;
 * - аббревиатуры органов («МВД», «УФМС», «ГУ», «ОВД», «СНТ», «АССР») — как есть заглавными;
 * - латинские двойники в русском тексте («P-H», «PECI.») — кириллицей.
 * Только для того, что прочитал сканер (`PassportText`, `Party::fillFromScan`): набранное руками не трогается.
 */
final class PassportCase
{
    /** Сокращения адреса и места: строчными, с точкой и без. */
    private const ABBR = ['г', 'гор', 'д', 'дер', 'с', 'п', 'пос', 'х', 'ст', 'ул', 'кв', 'корп', 'к', 'стр', 'обл', 'р', 'н', 'пр', 'т',
        'кт', 'просп', 'пгт', 'рп', 'мкр', 'мкрн', 'пер', 'наб', 'ш', 'б', 'бул', 'пл', 'туп', 'тер', 'им', 'респ', 'м', 'о', 'лит', 'сп',
        'нп', 'аул', 'ж', 'кп', 'сс', 'нас', 'пункт'];

    /** Предлоги и союзы: строчными (не первым словом). */
    private const SMALL = ['в', 'во', 'на', 'по', 'и', 'с', 'со', 'к', 'ко', 'у', 'при', 'от', 'до', 'за', 'из', 'о', 'об'];

    /** Аббревиатуры: заглавными, как в бланке. */
    private const UPPER = ['ГУ', 'МВД', 'УФМС', 'ОУФМС', 'ФМС', 'ОВД', 'УВД', 'ГУВД', 'РОВД', 'РУВД', 'ГОВД', 'ОМВД', 'УМВД', 'ГУМВД', 'ОВМ', 'ОУФМС',
        'ТП', 'МП', 'ПВС', 'ОП', 'СССР', 'АССР', 'ССР', 'РСФСР', 'РФ', 'СНТ', 'ДНТ', 'ТСН', 'ГСК', 'ЗАО', 'ОАО', 'ООО', 'МО', 'ЛО', 'ЛОВД', 'ЛУ',
        'УВМ', 'ОФМС', 'УФМСР', 'ОО', 'ТО', 'ФКУ', 'ВЧ', 'КБР', 'КЧР', 'ЯНАО', 'ХМАО', 'ЕАО', 'НАО'];

    /** Латиница, похожая на кириллицу: в русском тексте сканер путает. */
    private const TWINS = ['A' => 'А', 'B' => 'В', 'C' => 'С', 'E' => 'Е', 'H' => 'Н', 'K' => 'К', 'M' => 'М', 'O' => 'О', 'P' => 'Р', 'T' => 'Т',
        'X' => 'Х', 'Y' => 'У', 'I' => 'І'];

    public static function format(?string $s): ?string
    {
        if ($s === null || trim($s) === '') {
            return $s;
        }
        // Слово из одних латинских двойников в русском тексте — кириллицей («P-H» → «Р-Н»); «І» — это «П» обрывком («PECI.» → «РЕСП»).
        if (preg_match('/[А-ЯЁа-яё]/u', $s)) {
            $s = preg_replace_callback('/(?<![\p{L}])[ABCEHKMOPTXYI]+(?![\p{L}])/u', fn ($m) => strtr(strtr($m[0], self::TWINS), ['І' => 'П']), $s);
        }
        $first = true;
        $prev = null;

        return preg_replace_callback('/\p{L}+/u', function ($m) use ($s, &$first, &$prev) {
            [$word, $at] = $m[0];
            $isFirst = $first;
            $first = false;
            [$prevWord, $prevEnd] = $prev ?? ['', -2];
            $prev = [mb_strtolower($word), $at + strlen($word)];
            $before = $at > 0 ? substr($s, $at - 1, 1) : '';
            $after = substr($s, $at + strlen($word), 1);
            $lower = mb_strtolower($word);
            $upper = mb_strtoupper($word);
            // Буква номера дома или квартиры: «44А», «40"В"» — как есть.
            if (ctype_digit($before) || ($before === '"' && mb_strlen($word) === 1)) {
                return $upper;
            }
            if (in_array($upper, self::UPPER, true) && $word === $upper && ! in_array($lower, self::ABBR, true)) {
                return $upper;
            }
            // Хвост сокращения через дефис: «р-не», «р-на», «пр-та».
            if ($before === '-' && $prevEnd === $at - 1 && in_array($prevWord, self::ABBR, true) && mb_strlen($prevWord) <= 2) {
                return $lower;
            }
            // Сокращение: с точкой, в паре через дефис («р-н», «пр-т») или однобуквенное.
            if (in_array($lower, self::ABBR, true) && ($after === '.' || $after === '-' || $before === '-' || mb_strlen($lower) === 1 || in_array($lower, ['обл', 'ул', 'кв', 'пгт', 'рп', 'мкр', 'снт', 'днт', 'тсн', 'корп', 'стр', 'респ', 'пос', 'гор', 'дер'], true))) {
                return $lower;
            }
            if (! $isFirst && in_array($lower, self::SMALL, true)) {
                return $lower;
            }

            return mb_strtoupper(mb_substr($lower, 0, 1)).mb_substr($lower, 1);
        }, $s, flags: PREG_OFFSET_CAPTURE);
    }
}
