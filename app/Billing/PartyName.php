<?php

namespace App\Billing;

use App\Billing\Actions\SaveBuyerData;

/**
 * Имя плательщика в строке списка (17.11.2026, «Оплаты»: в одном столбце стояли «ОБЩЕСТВО С ОГРАНИЧЕННОЙ…» с обрезкой,
 * «ООО "МП-ТРАНС"», «Холопова Ирина Васильевна» и «Дмитрий Макаров»): форма собственности — сокращением (ООО, АО, ИП),
 * кавычки — ёлочками, человек — «Имя Фамилия», как имя аккаунта (`SaveBuyerData::nameParts`; порядок не понять — как
 * записано). Полное имя — в карточке и документах, здесь только вид.
 */
final class PartyName
{
    /** Длинная форма → сокращение; длинные первыми: «Непубличное акционерное общество» не должно стать «Непубличное АО». */
    private const FORMS = [
        'ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ' => 'ООО',
        'НЕПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО' => 'АО',
        'ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО' => 'ПАО',
        'ЗАКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО' => 'ЗАО',
        'ОТКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО' => 'ОАО',
        'АКЦИОНЕРНОЕ ОБЩЕСТВО' => 'АО',
        'ИНДИВИДУАЛЬНЫЙ ПРЕДПРИНИМАТЕЛЬ' => 'ИП',
    ];

    public static function short(?string $name): string
    {
        $s = trim(preg_replace('/\s+/u', ' ', (string) $name));
        if ($s === '') {
            return '';
        }
        // Прямые и «лапки» парами — ёлочками.
        $s = preg_replace('/["“”„]([^"“”„]+)["“”„]/u', '«$1»', $s);
        foreach (self::FORMS as $long => $abbr) {
            $s = preg_replace('/^'.str_replace(' ', '\s+', $long).'(?=\s|«|$)\s*/iu', $abbr.' ', $s, 1, $hit);
            if ($hit) {
                return trim($s);
            }
        }
        if (preg_match('/^(ООО|АО|ПАО|ЗАО|ОАО|ИП)\b/u', $s) || str_contains($s, '«')) {
            return $s;
        }
        // Человек: два-три слова из букв. Записан заглавными (паспорт, OCR) — с заглавной буквы.
        if (! preg_match('/^[\p{L}-]+( [\p{L}-]+){1,2}$/u', $s)) {
            return $s;
        }
        if (mb_strtoupper($s) === $s) {
            $s = mb_convert_case(mb_strtolower($s), MB_CASE_TITLE);
        }
        // Своё же имя «текущим»: два слова, порядок которых не понять, остаются как записаны («Армен Хачан» не перевернётся).
        $parts = SaveBuyerData::nameParts($s, $s);

        return $parts ? trim($parts[0].' '.$parts[1]) : $s;
    }
}
