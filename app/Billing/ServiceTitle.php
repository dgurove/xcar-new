<?php

namespace App\Billing;

/**
 * Что пишем в чеке разовой оплаты. По 54-ФЗ (ст. 4.7, тег 1030) наименование называет конкретную услугу: «Оплата»,
 * «Услуги», «Оплата по счёту № 15» — неполный реквизит чека. Ссылкой ЮKassa ПРАЙМ принимает только свои услуги по подбору
 * ТС: магазин одобрен под них, а займы, возвраты, залоги и деньги за машину или за третье лицо — не услуга (другие признаки
 * чека и агентские теги, ПРАЙМ не платёжный агент). Текст — от 10 до 128 знаков (предел позиции у ЮKassa).
 */
final class ServiceTitle
{
    public const DEFAULT = 'Консультационные услуги по подбору ТС';

    /** Подсказки чипами — только из того, чем ПРАЙМ занимается на xcar.ru. */
    public const PRESETS = [self::DEFAULT, 'Услуга подбора ТС', 'Проверка ТС перед покупкой', 'Организация осмотра ТС'];

    /**
     * Не услуга — целыми словами с окончаниями, а не началом слова: «долг» не должен ловить «долгосрочное», «перевод» —
     * «переводчика» и «перевод документов».
     */
    private const STOP = ['за[ий]м\p{L}*', 'заем\p{L}*', 'долг(а|и|у|ов|ом|ам|ами|ах)?', 'возврат\p{L}*', 'залог\p{L}*', 'депозит\p{L}*',
        'перевод(а|ы|ом)? (денег|средств|денежных средств)', 'денежн\p{L}* перевод\p{L}*', 'пополнени\p{L}*', 'штраф\p{L}*',
        'треть(е|его|ему|им) лиц\p{L}*', 'третьих лиц', 'за (автомобиль|машину|тс)', '(стоимость|покупк\p{L}|оплат\p{L}) (тс|автомобиля|машины)'];

    /** Слова, которые услугу не называют: если кроме них, чисел и дат ничего нет — это не наименование. */
    private const FILLER = ['оплата', 'оплаты', 'оплату', 'доплата', 'предоплата', 'аванс', 'платеж', 'платежа', 'по', 'за', 'от', 'на', 'и', 'в',
        'счету', 'счет', 'счета', 'договору', 'договор', 'услуги', 'услуга', 'услуг', 'года', 'год', 'г', 'месяц', 'январь', 'февраль', 'март',
        'апрель', 'май', 'июнь', 'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'];

    /** Ошибка словами или null — текст годится в чек. */
    public static function problem(string $title): ?string
    {
        $t = trim(preg_replace('/\s+/u', ' ', $title));
        $plain = str_replace('ё', 'е', mb_strtolower($t));
        if (mb_strlen($t) < 10) {
            return 'Назовите услугу: что именно оплачивают';
        }
        if (mb_strlen($t) > 128) {
            return 'Не длиннее 128 знаков: столько помещается в чек';
        }
        foreach (self::STOP as $pattern) {
            if (preg_match('/(?<!\p{L})'.$pattern.'(?!\p{L})/u', $plain)) {
                return 'Ссылкой принимаем только оплату наших услуг';
            }
        }
        $words = array_filter(preg_split('/[^\p{L}]+/u', $plain), fn ($w) => $w !== '' && ! in_array($w, self::FILLER, true));
        if (! $words) {
            return 'Назовите услугу: «'.$t.'» в чеке не годится';
        }

        return null;
    }
}
