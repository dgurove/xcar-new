<?php

namespace App\Billing;

/**
 * Что пишем в чеке разовой оплаты. По 54-ФЗ (ст. 4.7, тег 1030) наименование называет конкретную услугу: голое «Оплата»
 * или «Услуги» — неполный реквизит чека. Ссылкой ЮKassa ПРАЙМ принимает только свои услуги по подбору ТС: магазин одобрен
 * под них, а займы, возвраты, залоги и деньги за машину или за третье лицо — не услуга (другие признаки чека и агентские
 * теги, ПРАЙМ не платёжный агент). Текст — от 10 до 128 знаков (предел позиции у ЮKassa).
 */
final class ServiceTitle
{
    public const DEFAULT = 'Консультационные услуги по подбору ТС';

    /** Подсказки чипами — только из того, чем ПРАЙМ занимается на xcar.ru. */
    public const PRESETS = [self::DEFAULT, 'Услуга подбора ТС', 'Проверка ТС перед покупкой', 'Организация осмотра ТС'];

    private const STOP = ['займ', 'заем', 'долг', 'возврат', 'залог', 'депозит', 'перевод', 'пополнен', 'штраф', 'третье лицо', 'третьего лица', 'третьих лиц',
        'за автомобиль', 'за машину', 'за тс', 'стоимость тс', 'стоимость автомобиля', 'покупка тс', 'покупка автомобиля', 'оплата тс', 'оплата автомобиля'];

    private const BARE = ['оплата', 'услуги', 'услуга', 'по договору', 'оплата по договору', 'предоплата', 'аванс', 'оплата услуг', 'оплата по счету', 'доплата', 'платеж'];

    /** Ошибка словами или null — текст годится в чек. */
    public static function problem(string $title): ?string
    {
        $t = trim(preg_replace('/\s+/u', ' ', $title));
        $plain = str_replace('ё', 'е', mb_strtolower($t));
        if (mb_strlen($t) < 10) {
            return 'Назовите услугу: что именно оплачивают';
        }
        if (mb_strlen($t) > 128) {
            return 'Не длиннее 128 знаков: столько помещается в чек';
        }
        if (in_array(trim($plain, ' .,:;!-'), self::BARE, true)) {
            return 'Назовите услугу: «'.$t.'» в чеке не годится';
        }
        foreach (self::STOP as $word) {
            if (preg_match('/(^|[^\p{L}])'.preg_quote($word, '/').'/u', $plain)) {
                return 'Ссылкой принимаем только оплату наших услуг';
            }
        }

        return null;
    }
}
