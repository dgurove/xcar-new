<?php

namespace App\Workflow\Presets;

/**
 * Поставщик присылает контакты владельца автомобиля, менеджер связывается с ним, забирает автомобиль и прикладывает
 * подписанный ДКП. Покупатель менеджера платит собственнику по ДКП, который собираем мы, а менеджер нам — подбор
 * (`DealScheme::OwnerDkp`): после ДКП сделка ждёт его оплату, с этого шага и срок счёта (`StartSelectionDue`).
 *
 * Сначала согласие менеджера, потом письмо (15.11.2026, владелец: «когда письмо от Т-Страхования приходит, мы должны как и у
 * Альфы СНАЧАЛА у менеджера спросить, берёт ли он его в работу, и только после того как он подтвердил, мы можем отправить
 * письмо в Т-Страхование»; до того с 10.10.2026 согласия не было вовсе, и письмо уходило сразу после «Принять»).
 * «Подтверждение принято» → «Согласие менеджера» (вопрос с машиной и VIN, `StepAsk`) → «Беру в работу» → «Письмо о покупке»
 * — одинаковый текст «Прошу прислать контакты и данные для организации сделки» ответом на письмо Т-Страхования «Предлагаем
 * принять участие в оценке ТС», без суммы и машины (владелец: «не надо там ничего подставлять»). Ответ с контактом —
 * «Поставщик согласовал» галкой админа в «Показать менеджеру» (`Disclose`, 03.11.2026), с выбранными контактами менеджеру в
 * работу. Тот же маршрут у ПСБ, РСХБ и ЗЕСТ.
 */
final class TBank extends Route
{
    public function letters(): array
    {
        return parent::letters() + [
            'contacts' => [
                'name' => 'Поставщику: запрос контактов',
                'subject' => '{{ claim_ref }}',
                'body' => "Добрый день!\n\nПрошу прислать контакты и данные для организации сделки.\n\nС уважением,\nАндрей Кузнецов",
            ],
        ];
    }

    public function blocks(): array
    {
        return $this->saleBlocks();
    }

    public function stages(): array
    {
        $head = $this->head(agreed: [['Поставщик согласовал', 'staff', 'owner_contact']]);
        $head['claimed']['letter'] = 'contacts';
        $head['bidding']['exits'][0][2] = 'manager_confirm';
        $head['choosing']['exits'][0][2] = 'manager_confirm';
        // Согласие — перед письмом (порядок ключей — порядок этапов в блоке): сделка уже есть, машина продана.
        $head = array_slice($head, 0, array_search('claimed', array_keys($head), true), true) + ['manager_confirm' => [
            'name' => 'Согласие менеджера', 'block' => 'agreement', 'waits_for' => 'manager', 'deadline_source' => 'next_day_17', 'offer_state' => 'sold',
            'ask_title' => 'Подтвердите, что берёте в работу',
            'ask_text' => 'Подтверждение принято. Подтвердите, что берёте автомобиль в работу, после этого напишем поставщику',
            // Отказ — в приём: вход туда отменяет сделку и отклоняет подтверждение.
            'exits' => [['Беру в работу', 'manager', 'claimed'], ['Я передумал', 'manager', 'bidding']],
        ]] + $head;

        return $head + [
            // Порядок дела (06.10.2026, владелец: «сначала он отмечает, что связался со страхователем, потом — что
            // забрал машину»): связался → забрал → подписанный ДКП. Покупатель и ДКП готовятся параллельно — чек-листом
            // задачи (`cabinet.deals.step`), подписывают при передаче.
            'owner_contact' => [
                'name' => 'Связаться с владельцем', 'block' => 'pickup', 'waits_for' => 'manager', 'limit_minutes' => self::DAY,
                'ask_title' => 'Свяжитесь с владельцем',
                'ask_text' => 'Свяжитесь с владельцем автомобиля и договоритесь о передаче',
                'staff_fields' => [['label' => 'Владелец'], ['label' => 'Телефон владельца'], ['label' => 'Адрес автомобиля', 'type' => 'textarea']],
                'exits' => [['Связался с владельцем', 'manager', 'buyer_pickup']],
            ],
            'buyer_pickup' => [
                'name' => 'Забрать автомобиль', 'block' => 'pickup', 'waits_for' => 'manager', 'limit_minutes' => 3 * self::DAY,
                'ask_title' => 'Заберите автомобиль', 'ask_text' => 'Заберите автомобиль у владельца',
                'exits' => [['Автомобиль забрал', 'manager', 'dkp_signed'], ['Автомобиль передан', 'staff', 'dkp_signed']],
            ],
            'dkp_signed' => [
                'name' => 'Подписанный договор', 'block' => 'pickup', 'waits_for' => 'manager', 'limit_minutes' => 2 * self::DAY, 'asks' => 'document',
                'ask_title' => 'Приложите подписанный договор',
                'ask_text' => 'Приложите ДКП, подписанный собственником и покупателем. Без него сделка не закроется',
                'exits' => [['Договор приложен', 'manager', 'selection_pay']],
            ],
        ] + $this->selectionSegment('closed_won') + $this->tail();
    }
}
