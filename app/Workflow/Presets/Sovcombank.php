<?php

namespace App\Workflow\Presets;

/**
 * Продажа у Совкомбанка: всё — про обязанность.
 *
 * Автомобиль мы обязаны вывезти (маршрут вывоза у него запускается с
 * каждым предложением), значит обязаны и продать. Поэтому «подтверждений
 * нет» ведёт к покупателю от страховой, а не в архив. Срок страховой у
 * черновика — только красный срок: «Покупатель от поставщика» выбираем мы
 * сами (06.10.2026, владелец: «не надо автоматически отдавать покупателю от
 * страховой только потому что срок вышел, там не настолько строгие сроки»).
 *
 * Согласовывать покупку с поставщиком нечего (05.10.2026), и платить до получения
 * тоже (10.10.2026, владелец: «совком просит вывезти без оплаты; потом менеджер или
 * его покупатель платит на ООО ПРАЙМ, ПРАЙМ платит совкому», договор комиссии):
 * принятое подтверждение сразу ведёт к «Заберите автомобиль». Забрал — этап оплаты
 * сначала просит указать покупателя (без срока; у гаражной — ещё цену продажи,
 * когда продаст, `Deal::namesBuyer`), счёт ПРАЙМ и договор купли-продажи встают
 * вместе (`SyncDealInvoices`), дальше оплата, наша проверка, подписанный договор и
 * оплата поставщику нами. Гаражная ветка «платим мы» — только «взяли под себя»
 * («Отдать» в гараж без менеджера, `Give`).
 */
final class Sovcombank extends Route
{
    public function blocks(): array
    {
        $sale = $this->saleBlocks();
        // Порядок — порядок пути: лестница менеджера не возвращается к блоку, что стоит раньше текущего.
        return [
            'sale' => $sale['sale'],
            'pickup' => ['name' => 'Получение автомобиля', 'text' => 'Заберите автомобиль, платить до получения не нужно'],
            'payment' => ['name' => 'Оплата', 'text' => 'Укажите покупателя: счёт ПРАЙМ и договор купли-продажи придут вместе. Оплатите счёт'],
            'signing' => ['name' => 'Договор', 'text' => 'Приложите договор купли-продажи, подписанный покупателем'],
            'supplier' => ['name' => 'Расчёт с поставщиком', 'text' => 'ПРАЙМ оплачивает автомобиль поставщику'],
            'agreement_garage' => ['name' => 'Взяли под себя', 'text' => 'Автомобиль взяли себе: оплачиваем его поставщику и оформляем документы на ПРАЙМ'],
            'won' => $sale['won'],
            'nobody' => $sale['nobody'],
            'insurer_buyer' => ['name' => 'Покупатель от поставщика', 'text' => 'Срок истёк. Автомобиль передаётся покупателю, которого назвал поставщик'],
        ];
    }

    public function stages(): array
    {
        $stages = $this->head(
            nobody: 'insurer_buyer',
            draftExits: [['Покупатель от поставщика', 'staff', 'insurer_buyer']],
            draftDeadline: 'insurer_deadline',
            accepted: [['buyer_pickup', 'buyer'], ['garage_payment', 'garage']],
        )
            + [
                'buyer_pickup' => [
                    // Без срока: забрать — его интерес; часы и «Ваш ход» — у оплаты.
                    'name' => 'Менеджер забирает автомобиль', 'block' => 'pickup', 'waits_for' => 'manager', 'offer_state' => 'sold',
                    'ask_title' => 'Заберите автомобиль', 'ask_text' => 'Свяжитесь с владельцем, договоритесь о времени и заберите автомобиль. Платить до получения не нужно',
                    'exits' => [['Автомобиль забрал', 'manager', 'invoice'], ['Автомобиль передан', 'staff', 'invoice']],
                ],
                'invoice' => [
                    'name' => 'Оплата по счёту ПРАЙМ', 'block' => 'payment', 'waits_for' => 'manager', 'limit_minutes' => 5 * self::DAY, 'asks' => 'document',
                    'ask_title' => 'Оплатите счёт', 'ask_text' => 'Оплатите счёт ПРАЙМ по реквизитам и приложите платёжное поручение',
                    'exits' => [['Платёжное поручение приложено', 'manager', 'payment_check']],
                ],
                'payment_check' => [
                    // Деньги приходят ПРАЙМ: проверяем сами, поставщику писать не о чем.
                    'name' => 'Проверка оплаты', 'block' => 'payment', 'waits_for' => 'us', 'limit_minutes' => self::DAY,
                    'exits' => [['Оплата получена', 'staff', 'dkp_signed'], ['Оплата не поступила', 'staff', 'invoice']],
                ],
                'dkp_signed' => [
                    'name' => 'Подписанный договор', 'block' => 'signing', 'waits_for' => 'manager', 'limit_minutes' => 5 * self::DAY, 'asks' => 'document',
                    'ask_title' => 'Приложите подписанный договор', 'ask_text' => 'Приложите договор купли-продажи, подписанный покупателем',
                    'exits' => [['Договор приложен', 'manager', 'supplier_payment'], ['Договор получен', 'staff', 'supplier_payment']],
                ],
                'supplier_payment' => [
                    'name' => 'Оплата поставщику', 'block' => 'supplier', 'waits_for' => 'us', 'limit_minutes' => 2 * self::DAY, 'letter' => 'payment',
                    'staff_fields' => [['label' => 'Дата оплаты'], ['label' => 'Номер платёжки']],
                    'exits' => [['Поставщику оплачено', 'staff', 'closed_won']],
                ],
            ]
            + $this->insurerBuyer()
            + self::garageSegment(confirm: false)
            + $this->tail();
        $stages['garage_payment']['offer_state'] = 'sold';
        unset($stages['supplier_declined']);

        return $stages;
    }

    /**
     * Срок вышел — покупателя называет страховая. Менеджера здесь нет:
     * подтверждения не было или оно не сыграло. Сделка в базе не заводится —
     * покупатель и сумма записываются на этапе документов.
     */
    private function insurerBuyer(): array
    {
        return [
            'insurer_buyer' => [
                'name' => 'Запрос покупателя у поставщика', 'block' => 'insurer_buyer', 'waits_for' => 'supplier', 'limit_minutes' => 3 * self::DAY,
                // Без второго выхода автомобиль ждал бы покупателя вечно: назвать его обязан поставщик, а обязать его мы не можем.
                'exits' => [['Поставщик назвал покупателя', 'staff', 'insurer_papers'], ['Покупатель не найден', 'staff', 'no_bids']],
            ],
            'insurer_papers' => [
                // Sold — иначе «Сделка закрыта» недостижима: выдать можно только из сделки.
                'name' => 'Оформление сделки с покупателем поставщика', 'block' => 'insurer_buyer', 'waits_for' => 'us', 'limit_minutes' => 5 * self::DAY, 'offer_state' => 'sold',
                'staff_fields' => [['label' => 'Покупатель'], ['label' => 'Телефон покупателя'], ['label' => 'Сумма сделки']],
                'exits' => [['Документы подписаны', 'staff', 'insurer_release']],
            ],
            'insurer_release' => [
                'name' => 'Передача автомобиля покупателю поставщика', 'block' => 'insurer_buyer', 'waits_for' => 'us', 'limit_minutes' => 3 * self::DAY,
                'staff_fields' => [['label' => 'Кто получил автомобиль'], ['label' => 'Дата передачи']],
                'exits' => [['Автомобиль передан', 'staff', 'closed_won']],
            ],
        ];
    }
}
