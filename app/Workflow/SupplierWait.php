<?php

namespace App\Workflow;

/**
 * Что ждём от поставщика на этапе — словами для строки шага «Ждём от поставщика счёт» (16.11.2026, владелец про «письмо от 13.11,
 * ждём 2д 17ч»: «непонятно, какого письма мы ждём и зачем»). Своего поля у этапа нет: смысл ожидания — его выходы для сотрудника
 * («Поставщик просит реквизиты» / «Поставщик сразу выставил счёт» — ждём запрос реквизитов или счёт). По выходам, а не по
 * названию: этапы переименовывают в настройках. Не узнали — «ответ».
 */
final class SupplierWait
{
    /** Кусок подписи выхода (строчными) → что ждём, в винительном. Первое совпадение. */
    private const BY_EXIT = [
        'поставщик согласовал' => 'согласие на продажу',
        'просит реквизиты' => 'запрос реквизитов или счёт',
        'счёт от поставщика получен' => 'счёт',
        'оплата получена' => 'подтверждение оплаты',
        'запись подтверждена' => 'подтверждение записи',
        'договор готов' => 'договор',
        'документы получены' => 'документы',
        'назвал покупателя' => 'покупателя',
        'письмо поставщика пришло' => 'письмо',
    ];

    public static function what(Stage $stage): string
    {
        $labels = $stage->loadMissing('exits')->exits
            ->filter(fn (Outcome $e) => $e->actor === Actor::Staff)
            ->map(fn (Outcome $e) => mb_strtolower(trim($e->label)));
        foreach (self::BY_EXIT as $part => $what) {
            if ($labels->contains(fn (string $label) => str_contains($label, $part))) {
                return $what;
            }
        }

        return 'ответ';
    }
}
