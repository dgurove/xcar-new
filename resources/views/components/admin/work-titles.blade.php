{{-- Заголовки раздела «Работа»: Сделки, Гараж, Вывоз, Почта, Чаты, Оплаты. Число у заголовка одно и то же, открыт он или
     нет, — счётчик из Nav::badges (горящие, непрочитанные; таб «Работа» с 11.10.2026 — только непрочитанные чаты); 10.10.2026 владелец: «на табе 26, а
     внутри 42». Своё число (`count`) — только у раздела без бейджа (Гараж). На телефоне — одной строкой, лента
     листается вбок от края до края, текущий в кадре (`activePillIntoView`); 09.10.2026 владелец: в две строки шапка
     «Оплат» занимала полэкрана. С 13.11.2026 — колесом, как «Предложения». --}}
{{-- edge — лента до правого края экрана; рядом справа кнопка (почта: «Написать») — обрывается у неё. --}}
@props(['current', 'count' => null, 'edge' => true])
@php
    $badges = \App\Support\Nav::badges(auth()->user());
    // Модератору из «Работы» открыты «Сделки» (документы: сумма договора и ДКП, 14.11.2026) и почта по галке — остальные
    // заголовки вели бы в 404.
    $me = auth()->user();
    $titles = $me->canManageCrm() ? ['deals' => 'Сделки', 'garage' => 'Гараж', 'mail' => 'Почта', 'chats' => 'Чаты', 'money' => 'Оплаты']
        : array_filter(['deals' => $me->canEditDeals() ? 'Сделки' : null, 'mail' => $me->canCrmMail() ? 'Почта' : null]);
@endphp
{{-- Колесом, как вкладки «Предложений» (13.11.2026, владелец: «сделай в работе такой же пиздатый переключатель вкладок»): заголовок —
     текущий раздел, нажатие — все разделы колесом во весь экран (`x-ui.tab-title hrefs`). Числа — те же: бейдж раздела или своё. --}}
@php
    $counts = [];
    foreach ($titles as $key => $label) {
        $n = $badges['/work/'.$key] ?? ($key === $current ? $count : null);
        if ($n !== null) {
            $counts[$key] = $n;
        }
    }
@endphp
<div class="work-titles min-w-0">
    <x-ui.tab-title :pills="$titles" :pill="$current" :hrefs="collect($titles)->mapWithKeys(fn ($l, $k) => [$k => '/work/'.$k])->all()" :counts="$counts" fallback="Работа" id="work-tabs"/>
</div>
