{{-- Имя файла с приглушённым расширением (23.11.2026, владелец: «расширения типа .jpg давай приглушённо везде писать»): «эптс»
     обычным, «.pdf» — `file-ext`. Одна дверь для строк файлов (`x-ui.file`), вложений письма и архива; после переименования
     так же собирает `file_rename_controller`. --}}
@props(['name'])
@php
    $name = (string) $name;
    // Расширение — хвост «.pdf» до пяти знаков хоть с одной буквой: «Счёт от 12.11» без расширения — целиком обычным.
    $ext = preg_match('/(?<=.)\.(?=[a-z0-9]{0,4}[a-z])[a-z0-9]{1,5}$/iu', $name, $m) ? $m[0] : '';
    $dot = $ext === '' ? false : mb_strlen($name) - mb_strlen($ext);
@endphp
{{ $ext === '' ? $name : mb_substr($name, 0, $dot) }}@if ($ext !== '')<span class="file-ext">{{ $ext }}</span>@endif
