{{-- Машина на месте схемы — значок её типа (`Category::icon`), как в таблицах: стоя, без поворота (боком повёрнутая машина
     не читается), одной величины во всех местах. Легковые — серым (лайм на схеме — действие: куда поставить, что выбрано), остальные типы — своими цветами `.cat-*`.
     Та же раскладка в редакторе — `carIcon` в `resources/js/park/plan/geometry.js`. --}}
@props(['spot', 'category' => null])
@php
    // Значок — квадрат 256 (машина в нём во всю ширину) по короткой стороне места, не больше обычного места: в месте вдоль и
    // поперёк ряда и в широком грузовом машина одной величины (31.10.2026, владелец: «размер скачет — кажется, что одни
    // машины больше других»).
    $size = round(min($spot['w'], $spot['h'], \App\Park\Plan::W) * 0.84, 2);
    $cx = $spot['x'] + $spot['w'] / 2;
    $cy = $spot['y'] + $spot['h'] / 2;
@endphp
<g class="plan-car cat-{{ $category?->value ?? 'unknown' }}">
    {!! \App\Support\Icons::svg($category?->icon() ?? 'cat-car', false, '', 'x="'.($cx - $size / 2).'" y="'.($cy - $size / 2).'" width="'.$size.'" height="'.$size.'"') !!}
</g>
