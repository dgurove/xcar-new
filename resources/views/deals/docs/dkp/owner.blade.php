            .'паспорт серии '.$doc->v($pp['series'], 12).' № '.$doc->v($pp['number'], 20).', выдан '.$doc->v($pp['issued_at'], 25).' г. '
            .$doc->v($pp['issued_by'], 70).($pp['code'] ? ', код подразделения '.e($pp['code']) : '').', '
            .$doc->ending($p, 'именуем', 'ый', 'ая').' в дальнейшем «'.$role.'»,</p>';
    };
