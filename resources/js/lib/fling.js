// Скорость жеста листа — одно правило для шторки, листа документов и карточки строки (16.10.2026: у каждого был свой
// подсчёт, у документов — по шести последним замерам, у остальных — по 80 мс): px/мс по последним 80 мс, не по одному
// замеру — у отпускания пальца последний шаг бывает нулевым.
export function fling() {
    const pts = [];
    return {
        add(t, pos) {
            pts.push([t, pos]);
            while (pts.length > 2 && t - pts[0][0] > 80) pts.shift();
        },
        speed() {
            if (pts.length < 2) return 0;
            const [t0, p0] = pts[0], [t1, p1] = pts[pts.length - 1];
            return (p1 - p0) / Math.max(16, t1 - t0);
        },
    };
}
